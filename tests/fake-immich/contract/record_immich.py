# --- Record, with the exact queries ImmichClient sends ----------------------------------------
recorded = {}


def record(name, path, use_key=key, raw=False, headers=None):
    status, hdrs, body = call("GET", path, key=use_key, raw=raw, headers=headers)
    entry = {"path": path, "status": status, "content_type": hdrs.get("Content-Type", "")}
    if raw:
        entry["bytes"] = len(body) if isinstance(body, (bytes, bytearray)) else None
        entry["content_range"] = hdrs.get("Content-Range")
    else:
        entry["body"] = body
    recorded[name] = entry
    return body


