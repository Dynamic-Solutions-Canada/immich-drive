"""Seed a throwaway Immich with synthetic data and record the responses ImmichDrive reads.

Usage: python3 -I seed_and_record.py <base url> <output folder>
Synthetic only: generated images, users on example.invalid, test passwords. Run against a
throwaway server; it creates users and an API key.
"""
import json
import struct
import sys
import time
import urllib.error
import urllib.request
import uuid
import zlib
from pathlib import Path

BASE = sys.argv[1].rstrip("/") + "/api"
OUT = Path(sys.argv[2])
OUT.mkdir(parents=True, exist_ok=True)


def png(colour):
    w, h = 320, 240
    raw = b"".join(b"\x00" + bytes(colour) * w for _ in range(h))

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")


def call(method, path, body=None, token=None, key=None, raw=False, headers=None):
    data = None
    hdrs = {"Accept": "application/json"}
    if headers:
        hdrs.update(headers)
    if body is not None and not isinstance(body, bytes):
        data = json.dumps(body).encode()
        hdrs["Content-Type"] = "application/json"
    elif isinstance(body, bytes):
        data = body
    if token:
        hdrs["Authorization"] = f"Bearer {token}"
    if key:
        hdrs["x-api-key"] = key
    req = urllib.request.Request(BASE + path, data=data, headers=hdrs, method=method)
    try:
        with urllib.request.urlopen(req) as resp:
            content = resp.read()
            return resp.status, dict(resp.headers), (content if raw else (json.loads(content) if content else None))
    except urllib.error.HTTPError as err:
        content = err.read()
        try:
            parsed = json.loads(content)
        except Exception:
            parsed = content.decode(errors="replace")
        return err.code, dict(err.headers), parsed


def upload(token, name, created, colour):
    boundary = uuid.uuid4().hex
    parts = []
    for field, value in [("deviceAssetId", f"contract-{name}"), ("deviceId", "contract"), ("fileCreatedAt", created), ("fileModifiedAt", created)]:
        parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{field}"\r\n\r\n{value}\r\n'.encode())
    parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="assetData"; filename="{name}"\r\nContent-Type: image/png\r\n\r\n'.encode() + png(colour) + b"\r\n")
    parts.append(f"--{boundary}--\r\n".encode())
    status, _, body = call("POST", "/assets", b"".join(parts), token=token, headers={"Content-Type": f"multipart/form-data; boundary={boundary}"})
    assert status in (200, 201), (status, body)
    return body["id"]


def login(email, password):
    status, _, body = call("POST", "/auth/login", {"email": email, "password": password})
    assert status == 201, (status, body)
    return body["accessToken"]


